package cn.song.mybatisplus.visualizer.ui

import cn.song.mybatisplus.visualizer.generator.CrudColumn
import cn.song.mybatisplus.visualizer.generator.CrudKind
import cn.song.mybatisplus.visualizer.generator.CrudSqlGenerator
import cn.song.mybatisplus.visualizer.generator.CrudTableSpec
import com.intellij.testFramework.fixtures.BasePlatformTestCase
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue

/**
 * T-CrudSql 修复验证：CrudSqlGenerator 产出的 PreviewResult 必须能被 SqlPreviewPanel.showResult
 * 完整渲染（真机用户反馈：选择弹窗 OK 后预览窗口未打开——怀疑面板管线抛异常被 OK 按钮吞掉）。
 * 六种语句逐一喂真实面板，任一抛异常测试即红。JUnit3 惯例（testXxx 命名）。
 */
class CrudSqlPreviewPanelRenderTest : BasePlatformTestCase() {

    private fun spec() = CrudTableSpec(
        tableName = "user",
        columns = listOf(
            CrudColumn("id", isPrimaryKey = true, autoGenerated = true, quoteHint = false),
            CrudColumn("name", quoteHint = true),
            CrudColumn("age", quoteHint = false),
        ),
    )

    /** 渲染并返回面板（调用方负责 clear+dispose），异常原样上抛。BasePlatformTestCase 测试线程即 EDT。 */
    private fun renderOnEdt(kind: CrudKind): SqlPreviewPanel {
        val stmt = CrudSqlGenerator.generate(spec()).first { it.kind == kind }
        val panel = SqlPreviewPanel(project)
        panel.showResult(stmt.result)
        return panel
    }

    private fun disposeQuietly(panel: SqlPreviewPanel) {
        panel.clear()
        panel.dispose()
    }

    /**
     * T-UiFixGate9：等 rerender 派发的 exec 预暖链静止（在途标记先见置位、再候复位）后收尾。
     * 机理：链的 doc 写是 EDT 派发拍（setText→save 有 ~30ms「已改未存」窗口），若链跨出用例
     * 生命周期，测试边界迟到的 VFS 会话（fixture 重建/相邻 ExecDoc* 类 vf 删除重建的
     * root-model 刷新）命中该窗口即被 MemoryDiskConflictResolver 收集冲突，收尾 EDT 泵处理时
     * 抛 CompoundRuntimeException 杀无辜 victim（20261018 门禁三轮实录 + [PROBE-GATE9] 探针实锤）。
     * 泵 EDT 供派发拍执行；写收敛落在用例内，边界会话只见干净文档。
     */
    private fun awaitExecPrewarmQuiescence() {
        // 阶段一（≤2s）：等链起跑。链未起跑（池线程未调度/已被在途链吸收）则不空等。
        val phase1Start = System.currentTimeMillis()
        while (System.currentTimeMillis() - phase1Start < 2_000 &&
            !cn.song.mybatisplus.visualizer.execute.DataSourceSelector.execPrewarmInFlightForTest()
        ) {
            com.intellij.util.ui.UIUtil.dispatchAllInvocationEvents()
            Thread.sleep(10)
        }
        // 阶段二（≤10s）：等链收敛（写+refresh+findPsi 全部落定，refresh 会话已应用）。
        val deadline = System.currentTimeMillis() + 10_000
        while (System.currentTimeMillis() < deadline &&
            cn.song.mybatisplus.visualizer.execute.DataSourceSelector.execPrewarmInFlightForTest()
        ) {
            com.intellij.util.ui.UIUtil.dispatchAllInvocationEvents()
            Thread.sleep(10)
        }
        com.intellij.util.ui.UIUtil.dispatchAllInvocationEvents()
    }

    fun testPanelRendersAllCrudKindsWithoutException() {
        val present = CrudSqlGenerator.generate(spec()).map { it.kind }.toSet()
        for (kind in present) {
            val panel = try {
                renderOnEdt(kind)
            } catch (t: Throwable) {
                throw AssertionError("rendering failed for $kind: $t", t)
            }
            disposeQuietly(panel)
        }
    }

    fun testGeneratedSqlTextPresentAfterRender() {
        val panel = renderOnEdt(CrudKind.SELECT_ALL)
        try {
            val text = panel.editorForTest()?.document?.text
            assertTrue("rendered text=$text", text?.contains("SELECT") == true && text?.contains("user") == true)
        } finally {
            disposeQuietly(panel)
        }
    }

    /**
     * T-PreviewExecDs-01d：降级链第二级（内存 PSI 预览）的创建前提——PsiFileFactory
     * .createFileFromText 在项目 fixture 下必须产出非空 PsiFile（无 VFS 文件但补全载体可用）。
     * 项目内预览文件预热失败时 createEditor 借此保留补全/注释，不再一步掉到裸 document。
     */
    fun testInMemoryPreviewPsiAvailableAsFallback() {
        val panel = SqlPreviewPanel(project)
        try {
            val psi = panel.createPreviewFileForTest(project, "SELECT 1 FROM user")
            assertNotNull("内存 PSI 降级产物不应为 null", psi)
            assertTrue("内存 PSI 应含 SQL 文本", psi.text.contains("SELECT"))
        } finally {
            disposeQuietly(panel)
        }
    }

    fun testInsertBatchModelSurvivesRender() {
        val panel = renderOnEdt(CrudKind.INSERT)
        try {
            assertTrue(panel.currentForTest()?.batchModel != null)
        } finally {
            disposeQuietly(panel)
        }
    }

    fun testBatchCrudCarrierLosslesslyRerendersForActualTarget() {
        val panel = renderOnEdt(CrudKind.INSERT)
        try {
            val before = panel.currentForTest()?.effectiveDialect?.name
            assertTrue("expected MySQL baseline, got $before", before == "MySQL")
            assertTrue(panel.rerenderForExecutionTarget("PostgreSQL"))
            assertTrue(panel.currentForTest()?.batchModel?.dialect?.name == "PostgreSQL")
            assertTrue(panel.currentForTest()?.effectiveDialect?.name == "PostgreSQL")
            assertTrue(panel.lastRenderedSqlForTest()?.isNotBlank() == true)
            val request = panel.executionDialectGateRequest(
                cn.song.mybatisplus.visualizer.execute.ExecutionDialectGate.Intent.DML,
            )
            assertTrue(request.canLosslesslyRerender)
            assertTrue(request.userTextUntouched)
            // T-UiFixGate9：rerender 派发的预暖链收敛在本用例内，不跨边界（防冲突收集，见方法 KDoc）
            awaitExecPrewarmQuiescence()
        } finally {
            disposeQuietly(panel)
        }
    }
}
