    private fun assertFieldFillLayout(language: String) {
        val settings = PluginSettings.getInstance().state
        val oldLanguage = settings.language
        val oldCollapsed = SqlPreviewPanel.presetSectionCollapsed
        try {
            settings.language = language
            SqlPreviewPanel.presetSectionCollapsed = true
            val longSource = "auditCounterWithoutWhitespace".repeat(4)
            val preview = CrudSqlGenerator.generate(CrudTableSpec("fill_layout", listOf(
                CrudColumn("id", isPrimaryKey = true, autoGenerated = true, quoteHint = false),
                CrudColumn("created_at", quoteHint = true, fill = "INSERT"),
                CrudColumn(longSource, quoteHint = false, fill = "INSERT_UPDATE"),
            ))).first { it.kind == CrudKind.INSERT }.result
            val p = panel(preview)
            try {
                val scroll = p.paramScrollForTest()
                scroll.setSize(350, 420)
                fun layout(component: java.awt.Component) {
                    if (component is java.awt.Container) {
                        component.doLayout()
                        component.components.forEach(::layout)
                    }
                }
                fun bounds(component: java.awt.Component) = javax.swing.SwingUtilities.convertRectangle(
                    component.parent, component.bounds, scroll.viewport.view,
                )
                fun assertFits() {
                    repeat(3) { layout(scroll) }
                    val viewportWidth = scroll.viewport.extentSize.width
                    val controls = listOf(p.fieldFillCheckBox!!, p.fieldFillStatus!!) +
                        p.batchCheckBoxes + p.paramFields +
                        if (p.fieldFillEnabled) p.fieldFillFields.values else emptyList()
                    for (control in controls) {
                        val b = bounds(control)
                        assertTrue("$language ${control.name ?: control.javaClass.simpleName}: $b outside $viewportWidth",
                            b.width > 0 && b.height > 0 && b.x >= 0 && b.x + b.width <= viewportWidth)
                        val html = control.getClientProperty(javax.swing.plaf.basic.BasicHTML.propertyKey) as? javax.swing.text.View
                        if (html != null) {
                            assertTrue("Full text width must fit $b", html.getPreferredSpan(javax.swing.text.View.X_AXIS) <= b.width)
                            if (control is javax.swing.JCheckBox) {
                                assertTrue("Text plus checkbox icon must fit actual bounds", control.preferredSize.width <= b.width)
                            }
                            assertTrue("Full text height must fit ${control.name ?: control.javaClass.simpleName} $b; required=${html.getPreferredSpan(javax.swing.text.View.Y_AXIS)}", html.getPreferredSpan(javax.swing.text.View.Y_AXIS) <= b.height)
                        }
                    }
                    assertTrue("Safety switch stays at the left edge", bounds(p.fieldFillCheckBox!!).x <= 24)
                    assertFalse("350px must not need horizontal scrolling", scroll.horizontalScrollBar.isVisible)
                    assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.enabled"), visibleText(p.fieldFillCheckBox!!.text))
                    for (simulation in p.fieldFillFields.values) {
                        if (!p.fieldFillEnabled) continue
                        val ordinary = p.paramFields.single { it.getClientProperty(SqlPreviewPanel.PROP_FIELD_SOURCE) == simulation.name.removePrefix("fieldFill:") }
                        assertTrue("Simulation input has its own row", bounds(simulation).y >= bounds(ordinary).y + ordinary.height)
                    }
                    val rows = p.paramPanel.components.filter { it.isVisible }
                    rows.zipWithNext().forEach { (a, b) -> assertTrue("Rows must not overlap", a.y + a.height <= b.y) }
                    // Vertical scrolling reaches every input even when wrapped error text grows.
                    p.fieldFillFields.values.forEach { input ->
                        if (!p.fieldFillEnabled) return@forEach
                        scroll.viewport.viewPosition = java.awt.Point(0, 0)
                        val b = bounds(input)
                        (scroll.viewport.view as javax.swing.JComponent).scrollRectToVisible(b)
                        assertTrue("Input must be scroll-reachable", scroll.viewport.viewRect.contains(b))
                    }
                }
                assertFalse(p.fieldFillEnabled)
                assertFalse("AUTO id is not selected", "id" in p.enabledIds)
                assertFits()
                assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.status"), visibleText(p.fieldFillStatus!!.text))
                val normalStatusHeight = p.fieldFillStatus!!.height
                p.fieldFillFields.getValue(longSource).text = "1; DELETE FROM t"
                p.fieldFillCheckBox!!.doClick()
                assertFits()
                assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.invalid", longSource), visibleText(p.fieldFillStatus!!.text))
                assertTrue("Long error must increase the allocated row height", p.fieldFillStatus!!.height > normalStatusHeight)
                assertFalse(p.lastRenderedSqlForTest()!!.contains("DELETE"))
                assertFalse("Layout must not select AUTO id", "id" in p.enabledIds)
                p.fieldFillFields.getValue(longSource).text = "42"
                assertFits()
                assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.status"), visibleText(p.fieldFillStatus!!.text))
                assertEquals("Normal status must release the extra error height", normalStatusHeight, p.fieldFillStatus!!.height)
            } finally {
                p.clear()
            }
        } finally {
            settings.language = oldLanguage
            SqlPreviewPanel.presetSectionCollapsed = oldCollapsed
        }
    }

    fun testSimulationMessagesFollowSettingsLanguageAndBothBundlesDefineEveryKey() {
        val keys = listOf("enabled", "enabled.tooltip", "status", "annotation.tooltip",
            "value.tooltip", "value.label", "invalid").map { "fieldFill.simulation.$it" }
        val bundles = listOf("en" to "", "zh" to "_zh").associate { (language, suffix) ->
            val path = "/messages/MpSqlVisualizerBundle$suffix.properties"
            val stream = javaClass.getResourceAsStream(path) ?: error("Missing bundle $path")
            language to stream.bufferedReader(Charsets.UTF_8).use { reader ->
                java.util.Properties().apply { load(reader) }
            }
        }
        keys.forEach { key ->
            for ((language, properties) in bundles) {
                assertTrue("$language must explicitly define $key", properties.getProperty(key)?.isNotBlank() == true)
            }
            assertFalse("translations must differ for $key",
                bundles.getValue("en").getProperty(key) == bundles.getValue("zh").getProperty(key))
        }
        fun labels(component: java.awt.Component): List<javax.swing.JLabel> =
            (if (component is javax.swing.JLabel) listOf(component) else emptyList()) +
                (if (component is java.awt.Container) component.components.flatMap { labels(it) } else emptyList())
        val settings = PluginSettings.getInstance().state
        val previousLanguage = settings.language
        try {
            for (language in listOf("en", "zh")) {
                settings.language = language
                keys.filterNot { it.endsWith(".invalid") }.forEach { key ->
                    assertEquals(bundles.getValue(language).getProperty(key), MpSqlVisualizerBundle.message(key))
                }
                val p = panel()
                try {
                    assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.enabled"), visibleText(p.fieldFillCheckBox!!.text))
                    assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.enabled.tooltip"), p.fieldFillCheckBox!!.toolTipText)
                    assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.status"), visibleText(p.fieldFillStatus!!.text))
                    assertEquals(visibleText(p.fieldFillStatus!!.text), p.fieldFillStatus!!.toolTipText)
                    val rowLabels = labels(p.paramPanel)
                    assertTrue(rowLabels.any { it.text == MpSqlVisualizerBundle.message("fieldFill.simulation.value.label") })
                    val fillBoxes = p.batchCheckBoxes.filter { visibleText(it.text).contains("[fill=") }
                    assertEquals(2, fillBoxes.size)
                    fillBoxes.forEach {
                        assertTrue(
                            "角标应并入字段名文本：${visibleText(it.text)}",
                            visibleText(it.text).contains("[fill="),
                        )
                        assertTrue(
                            "角标注解 tooltip 应保留",
                            it.toolTipText.contains(MpSqlVisualizerBundle.message("fieldFill.simulation.annotation.tooltip")),
                        )
                    }
                    p.fieldFillFields.values.forEach {
                        assertEquals(MpSqlVisualizerBundle.message("fieldFill.simulation.value.tooltip"), it.toolTipText)
                    }
                    p.fieldFillFields.getValue("counter").text = "1; DELETE FROM t"
                    p.fieldFillCheckBox!!.doClick()
                    val invalid = MpSqlVisualizerBundle.message("fieldFill.simulation.invalid", "counter")
                    assertEquals(java.text.MessageFormat.format(bundles.getValue(language).getProperty("fieldFill.simulation.invalid"), "counter"), invalid)
                    assertEquals(invalid, visibleText(p.fieldFillStatus!!.text))
                    assertEquals(invalid, p.fieldFillStatus!!.toolTipText)
                    assertFalse(p.lastRenderedSqlForTest()!!.contains("DELETE"))
                } finally {
                    p.clear()
                }
            }
        } finally {
            settings.language = previousLanguage
        }
    }

