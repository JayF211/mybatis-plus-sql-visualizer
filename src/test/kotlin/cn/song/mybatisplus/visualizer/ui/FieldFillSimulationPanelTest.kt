package cn.song.mybatisplus.visualizer.ui

import cn.song.mybatisplus.visualizer.generator.*
import cn.song.mybatisplus.visualizer.model.FieldFillSimulation
import cn.song.mybatisplus.visualizer.model.PreviewResult
import cn.song.mybatisplus.visualizer.psi.BatchOperationConverter
import com.intellij.openapi.util.Disposer
import com.intellij.psi.PsiMethodCallExpression
import com.intellij.psi.util.PsiTreeUtil
import com.intellij.testFramework.fixtures.BasePlatformTestCase
import com.intellij.util.ui.UIUtil

class FieldFillSimulationPanelTest : BasePlatformTestCase() {
    override fun setUp() {
        super.setUp()
        cn.song.mybatisplus.visualizer.testutil.PluginSettingsTestSupport.resetToFactoryDefaults()
        ParamHistoryCache.clearPersistedHistory()
    }

    override fun tearDown() {
        try { ParamHistoryCache.clearPersistedHistory() } finally { super.tearDown() }
    }

    private fun result(kind: CrudKind = CrudKind.INSERT): PreviewResult = CrudSqlGenerator.generate(
        CrudTableSpec("fill_entity", listOf(
            CrudColumn("id", isPrimaryKey = true, autoGenerated = true, quoteHint = false),
            CrudColumn("stamp", quoteHint = true, fill = "INSERT_UPDATE"),
            CrudColumn("counter", quoteHint = false, fill = "INSERT_UPDATE"),
        )),
    ).first { it.kind == kind }.result

    private fun panel(result: PreviewResult = result()): SqlPreviewPanel = SqlPreviewPanel(project).also {
        Disposer.register(testRootDisposable, it)
        it.showResult(result)
        UIUtil.dispatchAllInvocationEvents()
    }

    fun testCrudRealRenderToggleLiteralValidationExplicitPriorityAndRestore() {
        val p = panel()
        val original = p.lastRenderedSqlForTest()
        assertFalse(p.fieldFillEnabled)
        p.fieldFillFields.getValue("stamp").text = "O'Reilly"
        p.fieldFillFields.getValue("counter").text = "42"
        assertEquals(original, p.lastRenderedSqlForTest())
        p.fieldFillCheckBox!!.doClick()
        assertTrue(p.lastRenderedSqlForTest()!!.contains("'O''Reilly'"))
        assertTrue(p.lastRenderedSqlForTest()!!.contains("42"))
        assertTrue(p.paramValues.values.none { it == "42" || it == "O'Reilly" })
        assertFalse("must not select AUTO id", "id" in p.enabledIds)
        p.paramValues["stamp"] = "explicit"
        p.renderSql()
        assertTrue(p.lastRenderedSqlForTest()!!.contains("'explicit'"))
        assertFalse(p.lastRenderedSqlForTest()!!.contains("Reilly"))
        p.paramValues.remove("stamp")
        p.fieldFillFields.getValue("counter").text = "1; DELETE FROM t"
        assertFalse(p.lastRenderedSqlForTest()!!.contains("DELETE"))
        assertTrue(p.lastRenderedSqlForTest()!!.contains("?"))
        assertTrue(p.fieldFillStatus!!.text.contains("counter"))
        p.fieldFillCheckBox!!.doClick()
        assertEquals(original, p.lastRenderedSqlForTest())
        p.clear()
    }

    fun testPresetsIndependentKeysClearAndHistoryFallbackNeverRestoreSimulation() {
        val p = panel()
        p.fieldFillFields.getValue("stamp").text = "sim"
        val snapshot = p.buildHistorySnapshot()
        assertEquals("sim", snapshot[FieldFillSimulation.SNAPSHOT_PREFIX + "stamp"])
        assertTrue(snapshot["stamp"].isNullOrEmpty())
        p.clearBatchValues()
        assertTrue(p.fieldFillValues.isEmpty())
        assertFalse(p.fieldFillEnabled)
        p.flushHistoryToCache()
        p.recallFromHistory()
        assertTrue(p.fieldFillValues.isEmpty())
        p.paramHistoryCache.save(p.historyCacheKey()!!, snapshot)
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertEquals("sim", p.fieldFillValues["stamp"])
        assertFalse("recall never enables simulation", p.fieldFillEnabled)
        p.paramHistoryCache.clear()
        p.historySnapshotFallbackSource = { snapshot }
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertTrue(p.fieldFillValues.isEmpty())
        assertFalse(p.paramValues.keys.any { it.startsWith(FieldFillSimulation.SNAPSHOT_PREFIX) })
        p.clear()
    }

    fun testNamedPresetSwitchDoesNotLeakSimulationIntoOtherScheme() {
        val p = panel()
        val key = p.historyCacheKey()!!
        p.fieldFillFields.getValue("stamp").text = "named-sim"
        p.fieldFillCheckBox!!.doClick()
        assertEquals(ParamHistoryCache.SchemeOpResult.OK,
            p.paramHistoryCache.saveAsScheme("with-fill", key, p.buildHistorySnapshot()))
        assertEquals(ParamHistoryCache.SchemeOpResult.OK,
            p.paramHistoryCache.saveAsScheme("without-fill", key, mapOf("stamp" to "explicit-preset")))
        p.switchToScheme("without-fill")
        assertTrue(p.fieldFillValues.isEmpty())
        assertFalse(p.fieldFillEnabled)
        p.switchToScheme("with-fill")
        assertEquals("named-sim", p.fieldFillValues["stamp"])
        assertFalse(p.fieldFillEnabled)
        p.clearBatchValues()
        p.flushHistoryToCache()
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertTrue(p.fieldFillValues.isEmpty())
        p.clear()
    }

    fun testClearGenerationRejectsOldPanelEditsSwitchFlushAndNewPanelRecall() {
        val p = panel()
        p.fieldFillFields.getValue("stamp").text = "old"
        p.fieldFillCheckBox!!.doClick()
        val oldSnapshot = p.buildHistorySnapshot()
        p.flushHistoryToCache()
        ParamHistoryCache.clearPersistedHistory()
        p.fieldFillFields.getValue("stamp").text = "late"
        p.flushHistoryToCache()
        assertTrue(p.buildHistorySnapshot().keys.none { it.startsWith(FieldFillSimulation.SNAPSHOT_PREFIX) })
        p.historySnapshotFallbackSource = { oldSnapshot }
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertTrue(p.fieldFillValues.isEmpty())
        p.clear()
        Disposer.dispose(p) // includes delayed history flush; old generation must remain invalid
        val next = panel()
        next.historySnapshotFallbackSource = { oldSnapshot }
        next.recallFromHistory()
        assertTrue(next.fieldFillValues.isEmpty())
        assertFalse(next.fieldFillEnabled)
        next.clear()
    }

    fun testEntityCrudActionSpecFeedsInsertAndUpdatePanels() {
        val file = myFixture.configureByText("CrudFill.java", """
            class CrudFill {
                @com.baomidou.mybatisplus.annotation.TableName("crud_fill")
                static class FillEntity {
                    @com.baomidou.mybatisplus.annotation.TableId Long id;
                    @com.baomidou.mybatisplus.annotation.TableField(fill=com.baomidou.mybatisplus.annotation.FieldFill.INSERT) String created;
                    @com.baomidou.mybatisplus.annotation.TableField(fill=com.baomidou.mybatisplus.annotation.FieldFill.UPDATE) String updated;
                }
            }
        """.trimIndent()) as com.intellij.psi.PsiClassOwner
        val entity = file.classes.single().innerClasses.single()
        val spec = cn.song.mybatisplus.visualizer.actions.GenerateCrudSqlFromEntityAction().entitySpec(entity)!!
        for (kind in listOf(CrudKind.INSERT, CrudKind.UPDATE)) {
            val p = panel(CrudSqlGenerator.generate(spec).first { it.kind == kind }.result)
            p.fieldFillFields.getValue("created").text = "insert-only"
            p.fieldFillFields.getValue("updated").text = "update-only"
            p.fieldFillCheckBox!!.doClick()
            val sql = p.lastRenderedSqlForTest()!!
            assertEquals(kind == CrudKind.INSERT, sql.contains("'insert-only'"))
            assertEquals(kind == CrudKind.UPDATE, sql.contains("'update-only'"))
            p.clear()
        }
    }

    fun testFreshPreviewRecallsLiteralButNotEnableStateAndExplicitRecallWins() {
        val p = panel()
        p.fieldFillFields.getValue("stamp").text = "sim"
        p.paramValues["stamp"] = "recalled-explicit"
        p.fieldFillCheckBox!!.doClick()
        p.flushHistoryToCache()
        p.showResult(result())
        assertFalse(p.fieldFillEnabled)
        assertEquals("sim", p.fieldFillFields.getValue("stamp").text)
        p.fieldFillCheckBox!!.doClick()
        assertTrue(p.lastRenderedSqlForTest()!!.contains("'recalled-explicit'"))
        assertFalse(p.lastRenderedSqlForTest()!!.contains("'sim'"))
        p.clear()
    }

    fun testMpBatchPsiMetadataFlowsIntoActualPanelAndUpdateWhereRemainsUnfilled() {
        for (method in listOf("saveBatch", "updateBatchById", "saveOrUpdateBatch")) {
            myFixture.configureByText("FillDemo.java", """
                class FillDemo {
                    void run(java.util.List<FillEntity> entities, Service service) { service.$method(entities); }
                    static class BaseService<T> {}
                    static class Service extends BaseService<FillEntity> {}
                    static class FillEntity {
                        @com.baomidou.mybatisplus.annotation.TableId Long id;
                        @com.baomidou.mybatisplus.annotation.TableField(fill=com.baomidou.mybatisplus.annotation.FieldFill.INSERT_UPDATE) String stamp;
                        @com.baomidou.mybatisplus.annotation.Version Integer version;
                    }
                }
            """.trimIndent())
            val call = PsiTreeUtil.findChildOfType(myFixture.file, PsiMethodCallExpression::class.java)!!
            val converted = BatchOperationConverter.convert(call, injectTenantLine = false)!!
            val batch = converted.batchModel!!
            assertEquals("INSERT_UPDATE", batch.toggleColumns.first { it.columnName == "stamp" }.fill)
            val preview = result().copy(sql = converted.sql, compactSql = converted.sql,
                unresolvedParams = converted.paramSources, paramHints = converted.paramHints, batchModel = batch)
            val p = panel(preview)
            val source = batch.toggleColumns.first { it.columnName == "stamp" }.source
            p.fieldFillFields.getValue(source).text = "simulated"
            p.fieldFillCheckBox!!.doClick()
            assertEquals(method != "saveOrUpdateBatch", p.lastRenderedSqlForTest()!!.contains("'simulated'"))
            if (method == "updateBatchById") {
                assertTrue(p.lastRenderedSqlForTest()!!.contains("id = ?"))
                assertTrue(p.lastRenderedSqlForTest()!!.contains("version = ?"))
            }
            p.setAllBatchColumns(false)
            assertFalse(p.lastRenderedSqlForTest()!!.contains("simulated"))
            p.clear()
        }
    }
}
