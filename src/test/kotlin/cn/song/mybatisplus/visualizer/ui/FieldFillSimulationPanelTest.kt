    fun testPresetsIndependentKeysClearAndHistoryFallbackNeverRestoreSimulation() {
        val p = panel()
        p.fieldFillFields.getValue("stamp").text = "sim"
        val snapshot = p.buildHistorySnapshot()
        assertEquals("sim", snapshot[FieldFillSimulation.SNAPSHOT_PREFIX + "stamp"])
        assertTrue(snapshot["stamp"].isNullOrEmpty())
        p.clearBatchValues()
        assertTrue(p.fieldFillValues.isEmpty())
        assertFalse(p.fieldFillEnabled)
        p.flushHistoryToCache()
        p.recallFromHistory()
        assertTrue(p.fieldFillValues.isEmpty())
        p.paramHistoryCache.save(p.historyCacheKey()!!, snapshot)
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertEquals("sim", p.fieldFillValues["stamp"])
        assertFalse("recall never enables simulation", p.fieldFillEnabled)
        p.paramHistoryCache.clear()
        p.historySnapshotFallbackSource = { snapshot }
        p.switchToScheme(ParamHistoryCache.DEFAULT_SCHEME)
        assertTrue(p.fieldFillValues.isEmpty())
        assertFalse(p.paramValues.keys.any { it.startsWith(FieldFillSimulation.SNAPSHOT_PREFIX) })
        p.clear()
    }

    fun testNamedPresetSwitchDoesNotLeakSimulationIntoOtherScheme() {
