package cn.song.mybatisplus.visualizer.testgen

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * M37.4 测试资产生成器单元测试（纯函数快照式断言）。
 * T-TestAssertReal：追加 A 档逐字回归（notNullColumns 空 = 存量输出逐字不变）与 B 档模板断言
 * （NOT NULL 清单注释、SELECT 校验骨架、count 前后对比占位）。
 */
class TestAssetGeneratorTest {

    private val input = TestAssetGenerator.Input(
        sql = "SELECT * FROM users WHERE id > 1",
        dialectName = "MySQL",
        tableName = "users",
        anchor = "UserController.java:87",
    )

    @Test
    fun `SQL 脚本含头注释与分号结尾目标语句`() {
        val asset = TestAssetGenerator.sqlScript(input, "20260902-120000")
        assertTrue(asset.fileName.startsWith("users-") && asset.fileName.endsWith(".sql"))
        assertTrue(asset.content.contains("-- 来源: UserController.java:87 | 方言: MySQL"))
        assertTrue(asset.content.contains("SELECT * FROM users WHERE id > 1;"))
        assertTrue(asset.content.contains("SELECT COUNT(*) AS matched FROM users;"))
        assertTrue(asset.content.contains("TODO"))
    }

    @Test
    fun `SQL 脚本无表名时断言为 TODO 注释`() {
        val asset = TestAssetGenerator.sqlScript(input.copy(tableName = null), "20260902-120000")
        assertTrue(asset.fileName.startsWith("generated-"))
        assertTrue(asset.content.contains("-- TODO: 补充前置数据与断言查询"))
        assertFalse(asset.content.contains("COUNT(*)"))
    }

    @Test
    fun `SQL 脚本多语句保留中间分号`() {
        val multi = "INSERT INTO t VALUES (1);INSERT INTO t VALUES (2)"
        val asset = TestAssetGenerator.sqlScript(input.copy(sql = multi), "x")
        assertTrue(asset.content.contains("INSERT INTO t VALUES (1);"))
        assertTrue(asset.content.contains("INSERT INTO t VALUES (2);"))
    }

    @Test
    fun `JUnit 骨架类名方法名由表名推导`() {
        val asset = TestAssetGenerator.junit(input, "20260902-120000")
        assertEquals("UsersGeneratedTest.java", asset.fileName)
        assertTrue(asset.content.contains("public class UsersGeneratedTest {"))
        assertTrue(asset.content.contains("void generatedUsers() {"))
        assertTrue(asset.content.contains("@org.junit.jupiter.api.Test"))
    }

    @Test
    fun `JUnit SQL 嵌入转义引号与换行`() {
        val tricky = "SELECT * FROM t WHERE name = \"a\"\n  AND b > 1"
        val asset = TestAssetGenerator.junit(input.copy(sql = tricky), "x")
        assertTrue(asset.content.contains("String sql = \"SELECT * FROM t WHERE name = \\\"a\\\"\\n  AND b > 1;\";"))
        assertFalse(asset.content.contains(tricky)) // 原始换行/引号不得原样嵌入
    }

    @Test
    fun `非法表名字符清洗为下划线`() {
        val asset = TestAssetGenerator.junit(input.copy(tableName = "ipm.RunPlan Project"), "x")
        // 类名首字母大写(合法 Java 标识符)
        assertEquals("Ipm_RunPlan_ProjectGeneratedTest.java", asset.fileName)
    }

    @Test
    fun `全非法表名回落默认名`() {
        val asset = TestAssetGenerator.sqlScript(input.copy(tableName = "!!!"), "x")
        assertTrue(asset.fileName.startsWith("generated-"))
        val j = TestAssetGenerator.junit(input.copy(tableName = "!!!"), "x")
        assertEquals("SqlVisualizerGeneratedTest.java", j.fileName)
    }

    // ---- T-TestAssertReal：A 档逐字回归（notNullColumns 空 = 存量输出逐字不变）----

    @Test
    fun `A档 SQL 脚本逐字不变`() {
        val asset = TestAssetGenerator.sqlScript(
            input.copy(notNullColumns = emptyList()), "20260902-120000",
        )
        assertEquals(
            "-- 来源: UserController.java:87 | 方言: MySQL | 生成: SQL Visualizer | 时间: 20260902-120000\n" +
                "-- 说明: 参数已回填为预览值，执行前请按需修改\n\n" +
                "SELECT * FROM users WHERE id > 1;\n\n" +
                "-- TODO: 补充前置数据后执行断言\n" +
                "SELECT COUNT(*) AS matched FROM users;\n",
            asset.content,
        )
    }

    @Test
    fun `A档 JUnit 骨架逐字不变`() {
        val asset = TestAssetGenerator.junit(
            input.copy(notNullColumns = emptyList()), "20260902-120000",
        )
        assertEquals(
            "// Generated by SQL Visualizer | 方言: MySQL | 来源: UserController.java:87 | 时间: 20260902-120000\n" +
                "// TODO: 粘贴到测试目录对应包；注入真实数据源（JdbcTemplate / MyBatis-Plus）后完善断言\n" +
                "public class UsersGeneratedTest {\n\n" +
                "    @org.junit.jupiter.api.Test\n" +
                "    void generatedUsers() {\n" +
                "        String sql = \"SELECT * FROM users WHERE id > 1;\";\n" +
                "        // TODO: 执行 sql 并断言结果（如 assertEquals(...)）\n" +
                "    }\n" +
                "}\n",
            asset.content,
        )
    }

    @Test
    fun `A档表名缺失优先于非空清单`() {
        // 防御组合：清单非空但表名缺失（调用侧不会构造，纯函数仍须落 A 档 TODO 分支）
        val asset = TestAssetGenerator.sqlScript(
            input.copy(tableName = null, notNullColumns = listOf("id")), "x",
        )
        assertTrue(asset.content.contains("-- TODO: 补充前置数据与断言查询"))
        assertFalse(asset.content.contains("前置数据须覆盖 NOT NULL 列"))
    }

    // ---- T-TestAssertReal：B 档模板（数据源查到目标表，NOT NULL 清单非空）----

    @Test
    fun `B档 SQL 脚本含非空清单与SELECT校验骨架`() {
        val asset = TestAssetGenerator.sqlScript(
            input.copy(notNullColumns = listOf("id", "name")), "20260902-120000",
        )
        assertTrue(asset.content.contains("-- 前置数据须覆盖 NOT NULL 列（来自数据源 schema）: id, name"))
        assertTrue(asset.content.contains("SELECT id, name FROM users;"))
        assertTrue(asset.content.contains("TODO: 补充前置数据后执行下方校验"))
        // A 档 matched 占位在 B 档不再出现
        assertFalse(asset.content.contains("SELECT COUNT(*) AS matched FROM users;"))
    }

    @Test
    fun `B档 SQL 脚本含count前后对比占位`() {
        val asset = TestAssetGenerator.sqlScript(
            input.copy(notNullColumns = listOf("id")), "20260902-120000",
        )
        assertTrue(asset.content.contains("SELECT COUNT(*) AS total_before FROM users;"))
        assertTrue(asset.content.contains("SELECT COUNT(*) AS total_after FROM users;"))
        assertTrue(asset.content.contains("-- TODO: 人工核对前后差值"))
        // 目标 SQL 同时出现在正文与 count 对比块（前后夹持）
        assertEquals(2, asset.content.split("SELECT * FROM users WHERE id > 1;").size - 1)
    }

    @Test
    fun `B档 JUnit 骨架含count前后骨架与断言占位`() {
        val asset = TestAssetGenerator.junit(
            input.copy(notNullColumns = listOf("id", "name")), "20260902-120000",
        )
        assertTrue(asset.content.contains("// 前置数据须覆盖 NOT NULL 列（来自数据源 schema）: id, name"))
        assertTrue(asset.content.contains("long countBefore = 0L; // TODO: 注入数据源后执行 SELECT COUNT(*) 前置统计"))
        assertTrue(asset.content.contains("long countAfter = 0L; // TODO: 注入数据源后执行 SELECT COUNT(*) 后置统计"))
        assertTrue(asset.content.contains("// TODO: assertEquals(预期差值, countBefore - countAfter); 人工核对前后差值"))
        // 零额外依赖：不出现 import / 注入字段等无法粘贴即编译的内容
        assertFalse(asset.content.contains("import "))
    }
}
