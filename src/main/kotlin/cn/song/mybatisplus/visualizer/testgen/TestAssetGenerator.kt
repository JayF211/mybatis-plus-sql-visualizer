package cn.song.mybatisplus.visualizer.testgen

/**
 * 测试资产生成结果（M37.4 / P-立项-06 N-4）。
 *
 * @param fileName 建议文件名（SQL 回归脚本落盘用；JUnit 形态仅作展示参考）
 * @param content  资产文本内容
 */
data class TestAsset(
    val fileName: String,
    val content: String,
)

/** 生成动作弹窗项（M37.4：单击即选；labelKey 指向 bundle 文案）。 */
sealed class GenAction(val labelKey: String) {
    data object SqlScript : GenAction("genTest.sqlScript")
    data object Junit : GenAction("genTest.junit")
}

/**
 * Wrapper 预览 → 测试资产生成器（纯函数，零平台依赖，可纯 JUnit 测试）。
 *
 * 双形态：
 *  - [sqlScript]：方言渲染后的目标 SQL + 断言查询骨架，落盘项目 `src/test/resources/sql-visualizer/`；
 *  - [junit]：可编译的 JUnit5 用例骨架（内嵌 SQL 常量 + TODO 断言位，零额外运行时依赖）。
 *
 * 边界（P-立项-06 计划）：不自动推导 INSERT 前置依赖数据（列级外键推导复杂度高，记 TODO）；
 * 不生成业务 Java 代码；时间戳等环境量由调用方注入保持纯函数。
 */
object TestAssetGenerator {

    /** 生成输入（纯数据）。 */
    data class Input(
        /** 方言渲染后的最终 SQL（可多语句；参数已回填为预览值）。 */
        val sql: String,
        /** 方言显示名（头注释用）。 */
        val dialectName: String,
        /** 表名（推断失败为 null；断言骨架与文件名推导用）。 */
        val tableName: String?,
        /** 来源描述（如 "UserController.java:87"；无则显示「预览面板」）。 */
        val anchor: String? = null,
    )

    /** SQL 回归脚本形态。 */
    fun sqlScript(input: Input, timestampLabel: String): TestAsset {
        val head = buildString {
            append("-- 来源: ").append(input.anchor ?: "预览面板")
            append(" | 方言: ").append(input.dialectName)
            append(" | 生成: SQL Visualizer | 时间: ").append(timestampLabel)
            append('\n')
            append("-- 说明: 参数已回填为预览值，执行前请按需修改")
        }
        val body = withTerminator(input.sql.trim())
        val assertion = if (input.tableName.isNullOrBlank()) {
            "\n\n-- TODO: 补充前置数据与断言查询"
        } else {
            "\n\n-- TODO: 补充前置数据后执行断言\nSELECT COUNT(*) AS matched FROM ${input.tableName};"
        }
        return TestAsset(fileName(input, timestampLabel, "sql"), "$head\n\n$body$assertion\n")
    }

    /** JUnit5 用例骨架形态（Java 文本；粘贴到测试目录对应包后编译）。 */
    fun junit(input: Input, timestampLabel: String): TestAsset {
        val className = testClassName(input.tableName)
        val methodName = testMethodName(input.tableName)
        val content = buildString {
            append("// Generated by SQL Visualizer | 方言: ").append(input.dialectName)
            append(" | 来源: ").append(input.anchor ?: "预览面板")
            append(" | 时间: ").append(timestampLabel)
            append('\n')
            append("// TODO: 粘贴到测试目录对应包；注入真实数据源（JdbcTemplate / MyBatis-Plus）后完善断言\n")
            append("public class ").append(className).append(" {\n\n")
            append("    @org.junit.jupiter.api.Test\n")
            append("    void ").append(methodName).append("() {\n")
            append("        String sql = \"").append(escapeJava(withTerminator(input.sql.trim()))).append("\";\n")
            append("        // TODO: 执行 sql 并断言结果（如 assertEquals(...)）\n")
            append("    }\n")
            append("}\n")
        }
        return TestAsset("$className.java", content)
    }

    private fun fileName(input: Input, timestampLabel: String, ext: String): String =
        "${sanitize(input.tableName) ?: "generated"}-$timestampLabel.$ext"

    private fun testClassName(tableName: String?): String {
        val base = sanitize(tableName) ?: return "SqlVisualizerGeneratedTest"
        return base.replaceFirstChar { it.uppercaseChar() } + "GeneratedTest"
    }

    private fun testMethodName(tableName: String?): String {
        val base = sanitize(tableName) ?: return "generated"
        return "generated" + base.replaceFirstChar { it.uppercaseChar() }
    }

    /** 文件名/标识符清洗：非法字符替换为下划线；全非法返回 null（回落默认名）。 */
    private fun sanitize(name: String?): String? {
        val cleaned = name?.trim()?.replace(Regex("[^A-Za-z0-9_-]"), "_")?.trimEnd('_')
        return cleaned?.takeIf { it.isNotEmpty() }
    }

    private fun withTerminator(sql: String): String =
        if (sql.isEmpty() || sql.endsWith(";")) sql else "$sql;"

    private fun escapeJava(s: String): String =
        s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\r", "").replace("\n", "\\n")
}
