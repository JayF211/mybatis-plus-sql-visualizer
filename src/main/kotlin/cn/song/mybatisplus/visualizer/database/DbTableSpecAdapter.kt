package cn.song.mybatisplus.visualizer.database

import cn.song.mybatisplus.visualizer.generator.CrudColumn
import cn.song.mybatisplus.visualizer.generator.CrudTableSpec
import cn.song.mybatisplus.visualizer.generator.DbTypeQuoteHint
import cn.song.mybatisplus.visualizer.psi.currentDialect
import cn.song.mybatisplus.visualizer.sql.IdentifierCaseSource
import com.intellij.database.model.DasColumn
import com.intellij.database.model.DasTable
import com.intellij.database.model.DasTableKey
import com.intellij.database.model.ObjectKind
import com.intellij.database.psi.DbTable

/**
 * DbTable → [CrudTableSpec] 适配器（T-CrudSql-03）。
 *
 * 自省元数据来源（2024.3.7.1 jar javap 实证）：
 *  - 列：`DasObject.getDasChildren(ObjectKind.COLUMN)` + `filterIsInstance<DasColumn>`（T-MarketInternal：
 *    原 `getDbChildren(Class, kind)` scheduled-for-removal，其方法体即 `getDasChildren(kind).filter(clazz)`）；
 *  - 主键：`getDasChildren(ObjectKind.KEY)` → `filterIsInstance<DasTableKey>` → `isPrimary()` →
 *    `getColumnsRef().names()`（模型类为 DasTableKey，无 DasKey 类）；
 *  - 自增：`DasTable.getColumnAttrs(col)` 含 [DasColumn.Attribute.AUTO_GENERATED]；
 *  - 类型/注释：`DasTypedObject.getDasType().toDataType().typeName`（T-MarketInternal：原
 *    `getDataType()` scheduled-for-removal，其方法体即 `getDasType().toDataType()`；类型名原文，
 *    引号提示走 [DbTypeQuoteHint] 启发）、`DasObject.getComment()`。
 *
 * 本类与 [DbTable] 类引用只经 database-optional.xml 的 action 到达——database 插件不在场时
 * 不实例化（Community 优雅降级，与 JoinVirtualFkProvider 同一加载面）；全部直引编译期类型，
 * 无反射入口，跨版本兼容由 verifyPlugin 三版本门禁兜底。
 */
object DbTableSpecAdapter {

    /** 自省表 → 统一表描述。逻辑删除/乐观锁在数据库侧无元数据，恒 null。 */
    fun toSpec(table: DbTable): CrudTableSpec {
        val das: DasTable = table.getDasObject()
        val primaryKeys = das.getDasChildren(ObjectKind.KEY)
            .filterIsInstance<DasTableKey>()
            .filter { it.isPrimary }
            .flatMap { it.getColumnsRef().names() }
            .toSet()
        val columns = das.getDasChildren(ObjectKind.COLUMN)
            .filterIsInstance<DasColumn>()
            .map { col ->
                CrudColumn(
                    columnName = col.name,
                    comment = col.comment?.takeIf { it.isNotBlank() },
                    isPrimaryKey = col.name in primaryKeys,
                    autoGenerated = DasColumn.Attribute.AUTO_GENERATED in das.getColumnAttrs(col),
                    quoteHint = DbTypeQuoteHint.decide(col.getDasType().toDataType().typeName),
                )
            }.toList()
        return CrudTableSpec(
            tableName = das.name,
            columns = columns,
            dialect = currentDialect(),
            // O-42：本类是目录来源的**唯一**入口——`das.name` / `col.name` 直取自省元数据，
            // 即字典里的真实大小写（真库实测：`all_tables.table_name` 对带引号创建的表返回
            // 小写 `issue_new`，未归一）。标记后 Oracle 按「含小写字母即加引号」引用，
            // 消除裸写折叠为大写导致的 ORA-00942。
            identifierCaseSource = IdentifierCaseSource.CATALOG,
        )
    }
}
