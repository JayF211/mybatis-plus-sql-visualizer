package cn.song.mybatisplus.visualizer.mcp;

import cn.song.mybatisplus.visualizer.reverse.GeneratedWrapper;
import cn.song.mybatisplus.visualizer.reverse.JavaCodeGenerator;
import cn.song.mybatisplus.visualizer.reverse.SqlReverseException;
import cn.song.mybatisplus.visualizer.reverse.SqlReverseParser;
import cn.song.mybatisplus.visualizer.reverse.SqlReverseResult;
import com.intellij.mcpserver.annotations.McpDescription;
import com.intellij.mcpserver.annotations.McpTool;
import com.intellij.mcpserver.annotations.McpToolHintValue;
import com.intellij.mcpserver.annotations.McpToolHints;

import java.util.Set;

/**
 * sqlv_reverse_sql 工具（T-McpToolset2 / T-MTS2-02，R2）：SQL → MyBatis-Plus 代码。
 *
 * 纯文本链：SqlReverseParser.parse（纯解析，错误带 offset）→ JavaCodeGenerator.generate
 * （entity=null 字符串列名 QueryWrapper 形态——零 PSI 候选反查；实体 lambda 形态属 IDE
 * 交互链，agent 面一期不提供，输出注明）。SELECT/UPDATE/DELETE/INSERT 与多表 JOIN 全支持。
 * 逻辑分层同 {@link SqlVisualizerCheckSqlTool}：{@link #reverseSql} 纯函数可测，挂起方法只做 audit 包装。
 *
 * T-MapResultVo：可选 `maps=true` + `mapperVariable` 生成 Map 响应形态调用行
 * （`xxxMapper.selectJoinMaps(wrapper)` / 分页 `selectJoinMapsPage(page, wrapper)`，
 * 返回 `List<Map<String, Object>>`；JoinMapper 1.5.8 javap 实证，不带 Class 参数）。
 * 两参数均有默认值——既有调用不传时行为逐字节不变。
 */
public class SqlVisualizerReverseSqlTool extends McpToolsetSupport {

    public SqlVisualizerReverseSqlTool() {
        super("sqlv_reverse_sql");
    }

    @McpTool(name = "sqlv_reverse_sql", title = "Convert SQL into MyBatis-Plus Java code")
    @McpDescription(
        description = "Convert a single SQL statement (SELECT / UPDATE / DELETE / INSERT, JOIN supported) into "
            + "MyBatis-Plus Java code — a QueryWrapper chain in string-column form, ready to paste. "
            + "Deterministic reverse generation from the parsed SQL structure; on parse failure the error "
            + "carries the line number and reason. Entity-typed LambdaQueryWrapper form (requires resolving "
            + "the entity class in the IDE) is available in the IDE's SQL-to-Java action. "
            + "Optional: pass maps=true with mapperVariable (e.g. \"deviceInfoMapper\") to also emit a "
            + "Map-result call line — selectJoinMaps(wrapper) for JOIN queries (selectMaps otherwise), "
            + "returning List<Map<String, Object>>. "
            + "Read-only: code generation only — never executes SQL."
    )
    @McpToolHints(
        readOnlyHint = McpToolHintValue.TRUE,
        destructiveHint = McpToolHintValue.FALSE,
        idempotentHint = McpToolHintValue.TRUE
    )
    public McpToolTextResult sqlv_reverse_sql(String sql, boolean maps, String mapperVariable) {
        return audit("sqlv_reverse_sql", () -> reverseSql(sql, maps, mapperVariable));
    }

    /** Kotlin 默认参数等价重载：maps/mapperVariable 缺省（既有调用零回归）。 */
    public String reverseSql(String sql) {
        return reverseSql(sql, false, "");
    }

    /** Kotlin 默认参数等价重载：mapperVariable 缺省空串。 */
    public String reverseSql(String sql, boolean maps) {
        return reverseSql(sql, maps, "");
    }

    /** 纯函数核心（零 IDE 依赖）。 */
    public String reverseSql(String sql, boolean maps, String mapperVariable) {
        if (sql.isBlank()) {
            throwExpected(McpToolErrors.code(McpToolErrors.INVALID_ARGUMENT, "sql is empty."));
        }
        SqlReverseResult result;
        try {
            result = SqlReverseParser.INSTANCE.parse(sql);
        } catch (SqlReverseException e) {
            int line = SqlReverseParser.lineOf(sql, e.getOffset());
            throwExpected(
                McpToolErrors.code(
                    McpToolErrors.INVALID_ARGUMENT,
                    "cannot parse SQL (line " + line + ", " + e.getKey() + "): " + e.getDetail()
                )
            );
            return null; // 不可达：throwExpected 必抛
        }
        if (maps && mapperVariable != null && !mapperVariable.isBlank()) {
            // T-MapResultVo：Map 响应形态调用行（join → MPJQueryWrapper 字符串形态 + selectJoinMaps；
            // 单表 → QueryWrapper + selectMaps）。VO 别名驱动属 IDE 交互链（需 VO 类上下文），agent 面不提供。
            JavaCodeGenerator.InvocationTarget invocation = new JavaCodeGenerator.InvocationTarget(
                mapperVariable,
                null,
                !result.joins().isEmpty(),
                Set.of(),
                true,
                null
            );
            StringBuilder out = new StringBuilder();
            out.append("// generated by sqlv_reverse_sql (string-column form, Map-result call)\n");
            out.append(JavaCodeGenerator.generate(result, null, GeneratedWrapper.QUERY, invocation));
            if (result.tableName() != null && !result.tableName().isBlank()) {
                out.append("\n\n// table: ").append(result.tableName());
            }
            return out.toString();
        }
        StringBuilder out = new StringBuilder();
        out.append("// generated by sqlv_reverse_sql (string-column QueryWrapper form)\n");
        out.append(JavaCodeGenerator.generate(result));
        if (result.tableName() != null && !result.tableName().isBlank()) {
            out.append("\n\n// table: ").append(result.tableName());
        }
        return out.toString();
    }
}
